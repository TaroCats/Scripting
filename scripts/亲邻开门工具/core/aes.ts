const RCON = new Uint8Array([0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36])

function xtime(a: number): number {
  return ((a << 1) ^ (a & 0x80 ? 0x1b : 0)) & 0xff
}

function expandKey(key: Uint8Array): Uint8Array {
  if (key.length !== 16) throw new Error("AES-128 需要 16 字节密钥")
  const w = new Uint8Array(176)
  w.set(key, 0)
  for (let i = 16, r = 0; i < 176; i += 4) {
    let t0 = w[i - 4], t1 = w[i - 3], t2 = w[i - 2], t3 = w[i - 1]
    if (i % 16 === 0) {
      // RotWord + SubWord + Rcon
      const tmp = t0
      t0 = SBOX[t1] ^ RCON[r]
      t1 = SBOX[t2]
      t2 = SBOX[t3]
      t3 = SBOX[tmp]
      r++
    }
    w[i] = w[i - 16] ^ t0
    w[i + 1] = w[i - 15] ^ t1
    w[i + 2] = w[i - 14] ^ t2
    w[i + 3] = w[i - 13] ^ t3
  }
  return w
}

function encryptBlock(w: Uint8Array, block: Uint8Array): Uint8Array {
  const s = new Uint8Array(16)
  for (let i = 0; i < 16; i++) s[i] = block[i] ^ w[i]

  for (let round = 1; round <= 10; round++) {
    // SubBytes
    for (let i = 0; i < 16; i++) s[i] = SBOX[s[i]]

    // ShiftRows（列主序：s[r + 4c]）
    let t: number
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t
    t = s[2]; s[2] = s[10]; s[10] = t
    t = s[6]; s[6] = s[14]; s[14] = t
    t = s[3]; s[3] = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = t

    // MixColumns（最后一轮不做）
    if (round !== 10) {
      for (let c = 0; c < 4; c++) {
        const i = c * 4
        const a0 = s[i], a1 = s[i + 1], a2 = s[i + 2], a3 = s[i + 3]
        const x = a0 ^ a1 ^ a2 ^ a3
        s[i] = a0 ^ x ^ xtime(a0 ^ a1)
        s[i + 1] = a1 ^ x ^ xtime(a1 ^ a2)
        s[i + 2] = a2 ^ x ^ xtime(a2 ^ a3)
        s[i + 3] = a3 ^ x ^ xtime(a3 ^ a0)
      }
    }

    // AddRoundKey
    const off = round * 16
    for (let i = 0; i < 16; i++) s[i] ^= w[off + i]
  }
  return s
}

/** PKCS#5（16 字节块即 PKCS#7）填充 */
function pad(data: Uint8Array): Uint8Array {
  const padLen = 16 - (data.length % 16)
  const out = new Uint8Array(data.length + padLen)
  out.set(data, 0)
  out.fill(padLen, data.length)
  return out
}

export function aes128EcbEncryptBytes(key: Uint8Array, plain: Uint8Array): Uint8Array {
  const w = expandKey(key)
  const padded = pad(plain)
  const out = new Uint8Array(padded.length)
  for (let i = 0; i < padded.length; i += 16) {
    out.set(encryptBlock(w, padded.subarray(i, i + 16)), i)
  }
  return out
}

/** 仅加密单块，无填充 —— 用于对标准测试向量做自检 */
export function aes128EcbEncryptBlockRaw(key: Uint8Array, block: Uint8Array): Uint8Array {
  return encryptBlock(expandKey(key), block)
}

export function hexToBytes(hex: string): Uint8Array {
  const clean = hex.replace(/\s+/g, "")
  if (clean.length % 2 !== 0) throw new Error("hex 长度必须为偶数")
  const out = new Uint8Array(clean.length / 2)
  for (let i = 0; i < out.length; i++) out[i] = parseInt(clean.slice(i * 2, i * 2 + 2), 16)
  return out
}

export function bytesToBase64(bytes: Uint8Array): string {
  const CH = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
  let out = ""
  for (let i = 0; i < bytes.length; i += 3) {
    const b0 = bytes[i]
    const b1 = bytes[i + 1]
    const b2 = bytes[i + 2]
    out += CH[b0 >> 2]
    out += CH[((b0 & 0x03) << 4) | ((b1 ?? 0) >> 4)]
    out += b1 === undefined ? "=" : CH[((b1 & 0x0f) << 2) | ((b2 ?? 0) >> 6)]
    out += b2 === undefined ? "=" : CH[b2 & 0x3f]
  }
  return out
}

export function utf8Bytes(s: string): Uint8Array {
  const out: number[] = []
  for (const ch of s) {
    let cp = ch.codePointAt(0)!
    if (cp < 0x80) out.push(cp)
    else if (cp < 0x800) out.push(0xc0 | (cp >> 6), 0x80 | (cp & 0x3f))
    else if (cp < 0x10000) out.push(0xe0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f))
    else out.push(0xf0 | (cp >> 18), 0x80 | ((cp >> 12) & 0x3f), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f))
  }
  return new Uint8Array(out)
}
